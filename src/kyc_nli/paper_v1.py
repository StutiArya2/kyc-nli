"""Build the manuscript's numbers from hash-pinned v1 records, never legacy caches."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

import yaml

from kyc_nli.data.io import file_digest, load_instances
from kyc_nli.languages import load_languages, repo_root
from kyc_nli.v1 import fingerprint, resolve, write_json

NAMES = {"exact_match": "Exact match", "rule_engine": "Rules",
         "local_xlmr": "Local XLM-R", "archived_xlmr": "Archived XLM-R"}
MACROS = {"exact_match": "Exact", "rule_engine": "Rule",
          "local_xlmr": "Local", "archived_xlmr": "Archive"}


def load_records(config_path: Path) -> tuple[dict, dict]:
    config = yaml.safe_load(resolve(config_path).read_text(encoding="utf-8"))
    records = {}
    for name, record in config["inputs"].items():
        path = resolve(Path(record["path"]))
        if file_digest(path) != record["sha256"]:
            raise ValueError(f"Paper input hash mismatch: {name}")
        records[name] = json.loads(path.read_text(encoding="utf-8"))
    if (records["evaluation"]["status"] != "COMPLETE"
            or records["selective"]["status"] != "COMPLETE"
            or records["evaluation"]["dataset_version"] != "synth_v1"
            or records["selective"]["dataset_version"] != "synth_v1"):
        raise ValueError("Only completed v1 evaluations may enter the paper")
    return config, records


def table(path: Path, columns: str, header: list[str], rows: list[list[str]]) -> None:
    body = ["% GENERATED by kyc-nli paper-v1; do not hand-edit.",
            r"\begin{tabular}{" + columns + "}", r"\toprule",
            " & ".join(header) + r" \\", r"\midrule"]
    body += [" & ".join(row) + r" \\" for row in rows]
    body += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(body) + "\n", encoding="utf-8")


def interval(point: float, low: float, high: float, scale: float = 1) -> str:
    precision = 3 if scale == 1 else 2
    return (f"{point * scale:.{precision}f} "
            f"[{low * scale:.{precision}f}, {high * scale:.{precision}f}]")


def run(config_path: Path) -> Path:
    config_path = resolve(config_path)
    config, records = load_records(config_path)
    paper = repo_root() / "paper"
    tables, figures = paper / "tables", paper / "figures"
    tables.mkdir(exist_ok=True)
    figures.mkdir(exist_ok=True)
    systems = records["evaluation"]["systems"]
    policies = records["selective"]["systems"]
    generated = []

    def emit(name, columns, header, rows):
        path = tables / f"{name}.tex"
        table(path, columns, header, rows)
        generated.append(path)

    manifest = records["dataset"]
    data_rows = []
    for split, n in manifest["split_sizes"].items():
        record = manifest["files"][split]
        path = Path(record["path"])
        if file_digest(path) != record["sha256"]:
            raise ValueError(f"Frozen split changed: {split}")
        instances = load_instances(path)
        data_rows.append([split.capitalize(), str(len({x.identity_id for x in instances})),
                          str(n), *[str(manifest["label_counts"][split][label])
                                    for label in ("entailment", "contradiction", "neutral")]])
    emit("tab_data", "lrrrrr", ["Split", "IDs", "Cases", "E", "C", "N"], data_rows)
    rows = []
    macros = {}
    for name, label in NAMES.items():
        row = systems[name]
        ci = row["macro_f1_ci"]
        f1 = interval(row["macro_f1"], ci["low"], ci["high"])
        macros[f"{MACROS[name]}Fone"] = f1
        macros[f"{MACROS[name]}WrongName"] = str(row["wrong_name_correct"])
        rows.append([label, f1, f"{row['contrast_consistency']:.3f}",
                     f"{row['wrong_name_correct']}/{row['wrong_name_n']}"])
    emit("tab_main", "llrr", ["System", "Macro-F1 [95\\% CI]", "Group", "Name C"], rows)
    emit("tab_class", "lrrr", ["System", "E F1", "C F1", "N F1"], [
        [NAMES[name], *[f"{systems[name]['per_class_f1'][label]:.3f}"
                       for label in ("entailment", "contradiction", "neutral")]]
        for name in NAMES])
    rows = []
    for code, spec in load_languages().items():
        for name in ("rule_engine", "local_xlmr", "archived_xlmr"):
            ci = systems[name]["per_language_macro_f1_ci"][code]
            rows.append([spec.name, NAMES[name], interval(ci["point"], ci["low"], ci["high"])])
    emit("tab_language", "lll", ["Language", "System", "Macro-F1 [95\\% CI]"], rows)
    phenomena = sorted(systems["local_xlmr"]["per_phenomenon_accuracy"])
    emit("tab_phenomena", "lrrrr", ["Phenomenon", *NAMES.values()], [
        [p.replace("_", r"\_"), *[f"{systems[n]['per_phenomenon_accuracy'][p]:.3f}"
                                  for n in NAMES]] for p in phenomena])
    rows = []
    for name in ("rule_engine", "local_xlmr", "archived_xlmr"):
        point = policies[name]["budgets"]["0.05"]
        test, uncertainty = point["test"], point["test_uncertainty"]
        review_ci, risk_ci = uncertainty["review_load_95_ci"], uncertainty["automated_error_95_ci"]
        review = interval(test["review_load"], *review_ci, scale=100)
        risk = interval(test["automated_error_rate"], *risk_ci, scale=100)
        macros[f"{MACROS[name]}Review"] = f"{test['review_load'] * 100:.2f}"
        macros[f"{MACROS[name]}Risk"] = f"{test['automated_error_rate'] * 100:.2f}"
        rows.append([NAMES[name], f"{point['threshold']:.6f}", review,
                     f"{test['automated_errors']}/{test['automated_n']}", risk,
                     "Yes" if test["point_estimate_meets_budget"] else "No"])
    emit("tab_policy", "lrlllc", ["System", "Threshold", "Review \\% [95\\% CI]",
                                   "Errors/auto", "Error \\% [95\\% CI]", "Meets"], rows)
    delta = records["selective"]["paired_review_differences"]["local_xlmr-rule_engine"]["0.05"]
    macros["ReviewSaving"] = interval(-delta["delta_model_minus_rule_review"],
                                      -delta["95_ci"][1], -delta["95_ci"][0], scale=100)
    paired = records["evaluation"]["paired_vs_rule"]
    emit("tab_paired", "ll", ["Comparison", "Paired macro-F1 difference [95\\% CI]"], [
        [NAMES[name] + " minus rules", interval(paired[name + "-rule_engine"]["delta"],
                                               paired[name + "-rule_engine"]["low"],
                                               paired[name + "-rule_engine"]["high"])]
        for name in ("local_xlmr", "archived_xlmr")])
    pilot = records["pilot"]
    macros.update({"PilotCases": str(pilot["n"]),
                   "PilotCandidates": str(pilot["candidate_label_n"]),
                   "PilotUnresolved": str(len(pilot["unresolved_case_ids"])),
                   "PilotDisputes": str(len(pilot["human_generator_disagreement_ids"]))})
    emit("tab_pilot", "lrrr",
         ["Language", "Initial pairs", "Definite pairs", "Conditional kappa"], [
        [load_languages()[code].name, str(row["n"]), str(row["both_definite_n"]),
         "undefined" if row["conditional_kappa"] is None else f"{row['conditional_kappa']:.2f}"]
        for code, row in pilot["initial_AB_per_language"].items()])
    numbers = paper / "numbers.tex"
    numbers.write_text("% GENERATED from pinned v1 artifacts.\n" + "\n".join(
        rf"\newcommand{{\{key}}}{{{value}}}" for key, value in macros.items()) + "\n",
        encoding="utf-8")
    generated.append(numbers)

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({"font.size": 9, "axes.spines.top": False,
                         "axes.spines.right": False, "pdf.fonttype": 42})

    def save(fig, name):
        for suffix in ("pdf", "png"):
            path = figures / f"{name}.{suffix}"
            fig.savefig(path, dpi=180, bbox_inches="tight")
            generated.append(path)
        plt.close(fig)

    fig, ax = plt.subplots(figsize=(3.4, 1.9))
    for i, name in enumerate(NAMES):
        row = systems[name]
        low, high = row["macro_f1_ci"]["low"], row["macro_f1_ci"]["high"]
        ax.errorbar(row["macro_f1"], i, xerr=[[row["macro_f1"] - low],
                                            [high - row["macro_f1"]]], fmt="o", capsize=4)
    ax.set_yticks(range(len(NAMES)), list(NAMES.values()))
    ax.invert_yaxis()
    ax.set_xlim(0, 1.02)
    ax.tick_params(labelsize=7)
    ax.set_xlabel("Macro-F1 on frozen v1 (95% group-bootstrap CI)", fontsize=7)
    ax.grid(axis="x", alpha=0.2)
    save(fig, "v1_classification")
    fig, axes = plt.subplots(1, 2, figsize=(6.5, 2.6))
    names = ["rule_engine", "local_xlmr", "archived_xlmr"]
    for i, name in enumerate(names):
        point = policies[name]["budgets"]["0.05"]
        for ax, value, bounds in zip(axes, ["review_load", "automated_error_rate"],
                                    ["review_load_95_ci", "automated_error_95_ci"], strict=True):
            p = point["test"][value] * 100
            low, high = [x * 100 for x in point["test_uncertainty"][bounds]]
            ax.errorbar(i, p, yerr=[[max(0, p - low)], [max(0, high - p)]],
                        fmt="o", capsize=4, color=["#555555", "#166b90", "#a25030"][i])
    for ax in axes:
        ax.set_xticks(range(3), ["Rules", "Local", "Archived"])
        ax.set_ylim(bottom=-0.3)
        ax.grid(axis="y", alpha=0.2)
    axes[0].set_ylabel("Review load (%)")
    axes[1].set_ylabel("Error among automated decisions (%)")
    axes[1].axhline(5, color="black", linestyle="--", linewidth=1, label="Requested budget")
    axes[1].legend(fontsize=7)
    fig.tight_layout(w_pad=2)
    save(fig, "v1_policy")
    # Record paper-specific provenance separately from the immutable experiment runs.
    output = resolve(Path(config["output_root"])) / datetime.now(timezone.utc).strftime(
        "%Y%m%dT%H%M%S.%fZ")
    output.mkdir(parents=True, exist_ok=False)
    write_json(output / "build.json", {"status": "COMPLETE", "seed": config["seed"],
                                      "inputs": config["inputs"],
                                      "implementation": fingerprint(Path(__file__)),
                                      "generated": {p.relative_to(paper).as_posix(): fingerprint(p)
                                                    for p in generated}})
    return output
