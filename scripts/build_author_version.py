"""Generate an author-visible preprint without changing anonymous review sources."""
from __future__ import annotations

from kyc_nli.languages import repo_root


def main() -> None:
    paper = repo_root() / "paper"
    if not (paper / "authors.tex").is_file():
        raise ValueError("Create local paper/authors.tex from authors.example.tex first")
    source = (paper / "main.tex").read_text(encoding="utf-8")
    mode, author = r"\usepackage[review]{acl}", r"\author{Anonymous submission}"
    if source.count(mode) != 1 or source.count(author) != 1:
        raise ValueError("Expected unique review-mode and anonymous-author markers")
    source = source.replace(mode, r"\usepackage[preprint]{acl}")
    source = source.replace(author, r"\input{authors}")
    bibliography = r"\bibliography{references}"
    if source.count(bibliography) != 1:
        raise ValueError("Expected a unique bibliography marker for code availability")
    source = source.replace(
        bibliography, "\\input{code_availability}\n\n" + bibliography,
    )
    (paper / "author_version.tex").write_text(
        "% GENERATED by scripts/build_author_version.py; edit main.tex/authors.tex.\n"
        + source, encoding="utf-8")
    print(paper / "author_version.tex")


if __name__ == "__main__":
    main()
