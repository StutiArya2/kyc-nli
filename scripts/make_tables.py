"""Write every table in the paper as LaTeX, from machine-written results.

    python scripts/make_tables.py        # -> paper/tables/*.tex

The paper \\input{}s these files and never types a result by hand, so a table
cannot drift from the figure beside it or from the run that produced it. Change
a result by re-running its command and then this script -- never by editing
paper/tables/, which is overwritten on every run.

    tab_data.tex         data/processed/synth_v0.manifest.json + the splits
    tab_main.tex         results/noise_robustness.json + selective-prediction.json
    tab_noise.tex        results/noise_robustness.json
    tab_language.tex     results/noise_robustness.json
"""

from __future__ import annotations

import json
import sys
from collections import Counter

from kyc_nli.data.io import load_instances
from kyc_nli.languages import load_languages, repo_root

ROOT = repo_root()
OUT = ROOT / "paper" / "tables"
SYSTEMS = ("exact_match", "rule_engine", "cross_encoder")
NAME = {
    "exact_match": "Exact match",
    "rule_engine": "Rule engine",
    "cross_encoder": "Cross-encoder (ours)",
}
LEVELS = ("clean", "light", "moderate", "heavy")


def _json(name: str) -> dict:
    path = ROOT / "results" / name
    if not path.exists():
        sys.exit(f"missing results/{name}; run the command named in this script's docstring")
    return json.loads(path.read_text(encoding="utf-8"))


def _write(name: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    header = (
        "% GENERATED by scripts/make_tables.py -- do not edit by hand.\n"
        "% Regenerate the result, then re-run the script.\n"
    )
    (OUT / name).write_text(header + body, encoding="utf-8", newline="\n")
    print(f"  wrote paper/tables/{name}")


def f3(x: float) -> str:
    return f"{x:.3f}"


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def ci(pair) -> str:
    return f"\\small[{pair[0]:.3f}, {pair[1]:.3f}]"


def best(values: dict[str, float], higher: bool = True) -> set[str]:
    target = max(values.values()) if higher else min(values.values())
    return {k for k, v in values.items() if abs(v - target) < 5e-4}


def bold_if(s: str, flag: bool) -> str:
    return f"\\textbf{{{s}}}" if flag else s


# --------------------------------------------------------------------------


def tab_data() -> None:
    manifest = json.loads(
        (ROOT / "data" / "processed" / "synth_v0.manifest.json").read_text(encoding="utf-8")
    )
    splits = {
        s: load_instances(ROOT / "data" / "processed" / f"synth_v0.{s}.jsonl")
        for s in ("train", "dev", "test")
    }
    by_label = manifest["counts"]["by_label"]
    langs = list(load_languages())

    rows = []
    for split, insts in splits.items():
        labels = Counter(i.label.value for i in insts)
        rows.append(
            f"{split.capitalize()} & {len({i.identity_id for i in insts})} & "
            f"{len({i.contrast_group_id for i in insts})} & {len(insts):,} & "
            f"{labels['entailment']:,} & {labels['contradiction']:,} & {labels['neutral']:,} \\\\"
        )
    total = (
        f"\\midrule\nTotal & {sum(len({i.identity_id for i in v}) for v in splits.values())} & "
        f"{manifest['contrast_groups']:,} & {manifest['n_instances']:,} & "
        f"{by_label['entailment']:,} & {by_label['contradiction']:,} & "
        f"{by_label['neutral']:,} \\\\"
    )
    body = (
        "\\begin{tabular}{lrrrrrr}\n\\toprule\n"
        "Split & Identities & Groups & Instances & E & C & N \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n" + total + "\n\\bottomrule\n\\end{tabular}\n"
    )
    _write("tab_data.tex", body)
    print(f"    ({len(langs)} languages, seed {manifest['generator_config']['seed']})")


def tab_main() -> None:
    noise = _json("noise_robustness.json")
    sel = _json("selective-prediction.json")
    level = noise.get("trained_at", "moderate")
    row = noise["levels"][level]
    systems = [s for s in SYSTEMS if s in row]

    f1 = {s: row[s]["macro_f1"] for s in systems}
    cons = {s: row[s]["contrast_consistency"] for s in systems}
    fmr = {s: row[s]["false_mismatch_rate"] for s in systems}
    rev = {s: row[s]["review_load"] for s in systems}

    budget = 0.05
    lines = []
    for s in systems:
        # DEV-TUNED, never the test-tuned oracle: the threshold is chosen on dev
        # and applied unchanged to test, and the cell reports the error it
        # actually produced there -- flagged when that overshoots the budget.
        tuned = (sel.get(s, {}).get("dev_tuned") or {}).get(str(budget))
        if tuned is None:
            at5_txt = "--"
        else:
            t = tuned["test"]
            miss = "$^{\\ddagger}$" if t["error_on_auto"] > budget else ""
            at5_txt = f"{pct(t['review_load'])} ({pct(t['error_on_auto'])}){miss}"
        lines.append(
            f"{NAME[s]} & {bold_if(f3(f1[s]), s in best(f1))} {ci(row[s]['macro_f1_ci'])} & "
            f"{bold_if(f3(cons[s]), s in best(cons))} & "
            f"{bold_if(pct(fmr[s]), s in best(fmr, higher=False))} & "
            f"{pct(rev[s])} & {at5_txt} \\\\"
        )
    body = (
        "\\begin{tabular}{lcccc c}\n\\toprule\n"
        " & Macro-F1 & Contrast & False & Review & Review @ \\\\\n"
        "System & {\\small[95\\% CI]} & consist. & mismatch \\% & load \\% & "
        "5\\% err.\\ \\% (err.) \\\\\n\\midrule\n"
        + "\n".join(lines)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    _write("tab_main.tex", body)


def tab_noise() -> None:
    noise = _json("noise_robustness.json")
    systems = [s for s in SYSTEMS if s in noise["levels"]["moderate"]]
    lines = []
    for s in systems:
        cells = []
        for lv in LEVELS:
            r = noise["levels"][lv][s]
            col = {k: noise["levels"][lv][k]["macro_f1"] for k in systems}
            cells.append(f"{bold_if(f3(r['macro_f1']), s in best(col))} {ci(r['macro_f1_ci'])}")
        lines.append(f"{NAME[s]} & " + " & ".join(cells) + " \\\\")

    paired = []
    for lv in LEVELS:
        cmp = noise["levels"][lv].get("_paired", {}).get("cross_encoder-rule_engine")
        if cmp is None:
            paired.append("--")
            continue
        sign = "+" if cmp["delta"] >= 0 else "$-$"
        # Built outside the f-string: a backslash inside an f-string expression
        # is a syntax error before Python 3.12, and the project supports 3.10.
        dagger = "" if cmp["significant"] else "$^{\\dagger}$"
        paired.append(f"{sign}{abs(cmp['delta']):.3f}{dagger}")
    body = (
        "\\begin{tabular}{lcccc}\n\\toprule\n"
        "System & Clean & Light & Moderate$^{*}$ & Heavy \\\\\n\\midrule\n"
        + "\n".join(lines)
        + "\n\\midrule\n$\\Delta$ ours $-$ rules & " + " & ".join(paired)
        + " \\\\\n\\bottomrule\n\\end{tabular}\n"
    )
    _write("tab_noise.tex", body)


def tab_language() -> None:
    noise = _json("noise_robustness.json")
    level = noise.get("trained_at", "moderate")
    row = noise["levels"][level]
    specs = load_languages()
    systems = [s for s in ("rule_engine", "cross_encoder") if s in row]
    header = " & ".join(specs[c].name for c in specs)
    lines = []
    for s in systems:
        cells = [f3(row[s]["per_language_macro_f1"].get(c, float("nan"))) for c in specs]
        lines.append(f"{NAME[s]} & " + " & ".join(cells) + " \\\\")
    body = (
        "\\begin{tabular}{l" + "c" * len(specs) + "}\n\\toprule\n"
        f"System & {header} \\\\\n\\midrule\n"
        + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"
    )
    _write("tab_language.tex", body)


TABLES = {"data": tab_data, "main": tab_main, "noise": tab_noise, "language": tab_language}


def main(argv: list[str]) -> int:
    for name in argv or list(TABLES):
        print(f"[{name}]")
        TABLES[name]()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
